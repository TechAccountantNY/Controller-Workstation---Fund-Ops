"""Write the Part 1 outputs: CSVs for everything, plus one human-readable
Markdown reconstruction assembled from the same frames (so the document can
never disagree with the data)."""
from __future__ import annotations

from pathlib import Path

import pandas as pd

from .config import AS_OF, OUTPUT_DIR, PERIOD


def _money(x) -> str:
    if x is None or (isinstance(x, float) and pd.isna(x)):
        return "—"
    return f"{x:,.0f}"


def _md_table(df: pd.DataFrame, cols: list[tuple[str, str]], money: set[str] = frozenset(), pct: set[str] = frozenset()) -> str:
    head = "| " + " | ".join(h for _, h in cols) + " |\n|" + "|".join("---:" if c in money or c in pct else "---" for c, _ in cols) + "|\n"
    body = ""
    for r in df.itertuples(index=False):
        d = r._asdict()
        cells = []
        for c, _ in cols:
            v = d[c]
            if c in money:
                cells.append(_money(v))
            elif c in pct:
                cells.append("—" if v is None or pd.isna(v) else f"{v:.2f}%")
            else:
                cells.append("" if v is None or (isinstance(v, float) and pd.isna(v)) else str(v).replace("|", "/"))
        body += "| " + " | ".join(cells) + " |\n"
    return head + body


def write_outputs(result, arrivals: pd.DataFrame, decisions: pd.DataFrame | None, out_dir: Path = OUTPUT_DIR) -> list[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    ctx, chk, roll = result.ctx, result.checks, result.roll
    written = []

    def w(name: str, df: pd.DataFrame):
        p = out_dir / name
        df.to_csv(p, index=False)
        written.append(p)

    w("messages.csv", pd.DataFrame([m.to_row() for m in ctx.messages]))
    w("arrivals.csv", arrivals)
    w("statements_parsed.csv", pd.DataFrame([s.to_row() for s in ctx.statements]))
    w("capital_activity.csv", roll.capital)
    w("rollforward_sleeves.csv", roll.sleeves)
    w("rollforward_master.csv", roll.master)
    w("rollforward_vehicles.csv", roll.vehicles)
    w("rollforward_vehicles_alt_scenario.csv", roll.scenario_vehicles)
    w("rollforward_complex.csv", roll.complex_)
    w("exceptions.csv", pd.DataFrame([e.to_row() for e in chk.exceptions]))
    w("checks_passed.csv", pd.DataFrame(chk.passes).assign(evidence=lambda d: d.evidence.apply(" | ".join)))
    w("assumptions.csv", pd.DataFrame(roll.assumptions))
    if decisions is not None:
        w("decision_log.csv", decisions)

    # ------------------------------------------------------------------ markdown
    sl = roll.sleeves
    veh = roll.vehicles
    cx = roll.complex_.set_index("line")["amount"]
    ms = roll.master.set_index("line")["amount"]
    md = [f"# Brindlewood complex — {PERIOD} reconstruction (as of {AS_OF:%d %b %Y})\n",
          "Generated by `python -m fundops run`. Every figure below is computed from the files in `data/assessment-pack/`; "
          "rows marked POLICY are modelling choices listed in `assumptions.csv`, not statement figures.\n",
          "## 1. Headline\n",
          f"- Complex NAV estimate: **${cx['Complex NAV — September estimate (Σ vehicles)']:,.0f}** "
          f"(August close ${cx['Complex NAV — August close (Σ vehicles)']:,.0f}); master fund ${ms['Master NAV — September estimate']:,.0f}.",
          f"- {cx['Share of master NAV on clean statements']:.1f}% of master NAV rests on statements that tie internally, to prior close and to the fee schedule; "
          f"the rest is one disputed statement (Stonebow) and one missing statement (Wrenfield, carried flat).",
          f"- Upside if the disputed sleeve items resolve to the alternative reading: ${cx['Range: upside if disputed sleeve items resolve']:,.0f}.",
          f"- Cash of ${cx['Cash held unallotted (excluded from NAV)']:,.0f} is sitting in a subscription account and is **not** in NAV.",
          f"- {len(chk.exceptions)} exceptions ({sum(e.severity == 'critical' for e in chk.exceptions)} critical, "
          f"{sum(e.severity == 'high' for e in chk.exceptions)} high); {len(chk.passes)} checks passed.\n",
          "## 2. Sleeve roll-forward (master fund)\n",
          _md_table(sl, [("sleeve", "Sleeve"), ("aug_close_nav", "Aug close"), ("sep_opening_per_manager", "Sep open (mgr)"),
                         ("opening_tie_diff", "Open Δ"), ("net_return_pct", "Return"), ("sep_closing_per_manager", "Sep close (mgr)"),
                         ("estimate_nav", "Estimate"), ("alt_nav", "Alternative"), ("estimate_source", "Source"), ("confidence", "Conf.")],
                    money={"aug_close_nav", "sep_opening_per_manager", "opening_tie_diff", "sep_closing_per_manager", "estimate_nav", "alt_nav"},
                    pct={"net_return_pct"}),
          "\nBasis per sleeve:\n",
          "\n".join(f"- **{r.sleeve}**: {r.estimate_basis} — `{r.source_doc}`" for r in sl.itertuples()),
          "\n## 3. Master fund\n",
          _md_table(roll.master, [("line", "Line"), ("amount", "USD"), ("basis", "Basis")], money={"amount"}),
          "\n## 4. Vehicles\n",
          _md_table(veh, [("vehicle", "Vehicle"), ("aug_nav", "Aug NAV"), ("master_pnl_share", "Master P&L share"), ("direct_coinvest_pnl", "Direct P&L"),
                          ("subscriptions", "Subs"), ("redemptions", "Reds"), ("admin_fee_accrual", "Admin fee"), ("sep_nav_estimate", "Sep NAV est."),
                          ("sep_return_pct", "Return (net, ex-flows)"), ("cash_held_unallotted", "Cash held (ex-NAV)")],
                    money={"aug_nav", "master_pnl_share", "direct_coinvest_pnl", "subscriptions", "redemptions", "admin_fee_accrual", "sep_nav_estimate", "cash_held_unallotted"},
                    pct={"sep_return_pct"}),
          "\nBasis: " + veh.basis.iloc[0] + ".",
          ("\n" + "\n".join(f"- {r.vehicle}: {r.direct_basis}" for r in veh.itertuples() if r.direct_basis)) if veh.direct_basis.any() else "",
          f"\nAlternative scenario (`{roll.scenario_vehicles.scenario.iloc[0]}` — Kestrel Point redemption processed at 30 Sep as the TA queued it):\n",
          _md_table(roll.scenario_vehicles, [("vehicle", "Vehicle"), ("redemptions", "Reds"), ("sep_nav_estimate", "Sep NAV est.")],
                    money={"redemptions", "sep_nav_estimate"}),
          "\n## 5. Complex\n",
          _md_table(roll.complex_, [("line", "Line"), ("amount", "USD / %")], money={"amount"}),
          "\n## 6. Capital activity — where each item stands\n",
          _md_table(roll.capital, [("item", "Item"), ("kind", "Kind"), ("investor", "Investor"), ("vehicle", "Vehicle"), ("instructed", "Instructed"),
                                   ("received", "Received"), ("difference", "Δ"), ("dealing_date", "Dealing"), ("funds_value_date", "Funds value"),
                                   ("ta_acknowledged", "TA ack"), ("status", "Status"), ("nav_effect", "NAV effect")],
                    money={"instructed", "received", "difference", "nav_effect"}),
          "\n## 7. Exceptions, ranked\n",
          "Severity first; within severity, items needing a decision first, then dollars at stake. Full text in `exceptions.csv`.\n",
          _md_table(pd.DataFrame([dict(rank=e.rank, severity=e.severity, category=e.category.replace("_", " "), title=e.title,
                                       amount=e.amount_impact_usd, decide="yes" if e.decision_required else "", evidence="; ".join(e.evidence))
                                  for e in chk.exceptions]),
                    [("rank", "#"), ("severity", "Severity"), ("category", "Kind"), ("title", "Exception"), ("amount", "$ at stake"), ("decide", "Decision?"), ("evidence", "Evidence")],
                    money={"amount"}),
          "\n### Detail\n",
          "\n".join(f"**{e.rank}. [{e.severity.upper()}] {e.title}**  \n{e.detail}  \n*Recommended:* {e.recommended_action}  \n*Evidence:* {', '.join('`' + x + '`' for x in e.evidence)}\n"
                    for e in chk.exceptions),
          "\n## 8. What was checked and passed\n",
          _md_table(pd.DataFrame(chk.passes).assign(evidence=lambda d: d.evidence.apply(", ".join)),
                    [("check", "Check"), ("subject", "Subject"), ("detail", "Detail"), ("evidence", "Evidence")]),
          "\n## 9. Arrivals — what has come in and what is outstanding\n",
          _md_table(arrivals.assign(expected_by=arrivals.expected_by.astype(str), received_on=arrivals.received_on.astype(str).replace({"None": "", "NaT": ""})),
                    [("item", "Item"), ("expected_by", "Expected by"), ("received_on", "Received"), ("status", "Status"), ("document", "Document")]),
          "\n## 10. Modelling assumptions\n",
          _md_table(pd.DataFrame(roll.assumptions), [("key", "Assumption"), ("statement", "Setting"), ("reason", "Reason")]),
          ]
    if decisions is not None and len(decisions):
        md += ["\n## 11. Decision log (human-in-the-loop)\n",
               _md_table(decisions, [("rank", "#"), ("exception_key", "Exception"), ("disposition", "Disposition"), ("decided_by", "By"),
                                     ("decided_at", "When"), ("rationale", "Rationale")])]
    p = out_dir / "PART1_RECONSTRUCTION.md"
    p.write_text("\n".join(md), encoding="utf-8")
    written.append(p)
    return written
